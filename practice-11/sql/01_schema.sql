-- Схема базы задач. Скрипт запускается в новой пустой базе tip_tasks.
-- Не добавлять DROP, IF NOT EXISTS или COMMIT: транзакцией управляет psql -1.

CREATE TABLE public.categories (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  CONSTRAINT categories_pkey PRIMARY KEY (id),
  CONSTRAINT categories_id_positive CHECK (id > 0),
  CONSTRAINT categories_name_unique UNIQUE (name),
  CONSTRAINT categories_name_length
    CHECK (char_length(name) BETWEEN 1 AND 100 AND name = btrim(name))
);

CREATE TABLE public.tasks (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  title text NOT NULL,
  completed boolean NOT NULL DEFAULT false,
  priority text NOT NULL,
  category_id integer NOT NULL,
  CONSTRAINT tasks_pkey PRIMARY KEY (id),
  CONSTRAINT tasks_id_positive CHECK (id > 0),
  CONSTRAINT tasks_title_length
    CHECK (char_length(title) BETWEEN 1 AND 100 AND title = btrim(title)),
  CONSTRAINT tasks_priority_allowed
    CHECK (priority IN ('low', 'medium', 'high')),
  CONSTRAINT tasks_category_fk
    FOREIGN KEY (category_id)
    REFERENCES public.categories (id)
    ON DELETE RESTRICT
);

CREATE INDEX tasks_category_id_idx
  ON public.tasks (category_id);
